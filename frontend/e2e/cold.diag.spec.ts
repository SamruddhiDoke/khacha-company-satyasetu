import { expect, test } from "@playwright/test";
// Production cold-start journey (COLD=1). Run after the backend has been idle long enough to sleep.
test.skip(!process.env.COLD, "diagnostic");
test("cold start: page recovers by itself and completes a real fact-check", async ({ page }, info) => {
  test.skip(info.project.name !== "desktop");
  test.setTimeout(600_000);
  const t0 = Date.now();
  const log = (s: string) => console.log(`${((Date.now() - t0) / 1000).toFixed(1)}s ${s}`);
  const errs: string[] = [];
  page.on("console", (m) => m.type() === "error" && errs.push(m.text().slice(0, 120)));
  page.on("response", (r) => r.url().includes("/api/") && r.status() >= 400 && log(`RES ${r.status()} ${new URL(r.url()).pathname}`));
  await page.goto("/");
  const banner = page.getByTestId("waking-banner");
  const sawBanner = await banner.waitFor({ state: "visible", timeout: 12_000 }).then(() => true).catch(() => false);
  log(`waking banner shown: ${sawBanner}`);
  await expect(banner).toBeHidden({ timeout: 200_000 });
  log("banner gone / app ready");
  const visibleErrors = await page.locator("[role=alert]").allInnerTexts();
  log(`error toasts after recovery: ${JSON.stringify(visibleErrors)}`);
  const claim = "The Gateway of India in Mumbai was completed in 1924.";
  await page.getByLabel("Message").fill(claim);
  await page.keyboard.press("Enter");
  const bubble = page.getByTestId("message").filter({ hasText: claim });
  await expect(bubble).toBeVisible({ timeout: 60_000 });
  const vreq = page.waitForResponse((r) => r.url().includes("/verifications") && r.request().method() === "POST");
  await bubble.getByTestId("verify-button").click();
  const job = await (await vreq).json();
  log(`verify POST -> job ${job.id}`);
  await expect(bubble.getByTestId("verify-result").or(bubble.getByTestId("verify-failed"))).toBeVisible({ timeout: 330_000 });
  const d = await page.request.get(`/api/verifications/${job.id}`).then((r) => r.json());
  log(`RESULT ${d.status} ${d.overall_verdict} ${d.evidence_strength} err=${d.error_code} models=${JSON.stringify(d.models_used)} usage=${JSON.stringify(d.usage)}`);
  for (const c of d.claims) log(`CLAIM ${c.original_text} -> ${c.verdict} counted=${c.evidence.filter((e: any) => e.counted).length}`);
  log(`CITED ${JSON.stringify(d.sources.filter((s: any) => s.label).map((s: any) => [s.label, s.domain, s.tier]))}`);
  const q = d.claims.flatMap((c: any) => c.evidence.filter((e: any) => e.counted)).slice(0, 2).map((e: any) => e.quote.slice(0, 150));
  log(`QUOTES ${JSON.stringify(q)}`);
  await page.reload();
  await expect(page.getByTestId("message").filter({ hasText: claim })).toBeVisible({ timeout: 60_000 });
  log(`after reload: message still listed with result = ${await page.getByTestId("message").filter({ hasText: claim }).getByTestId("verify-result").isVisible()}`);
  log(`console errors: ${JSON.stringify(errs)}`);
});
